#!/usr/bin/env bash
# Office test install helper. Run from anywhere: infra/trial/office.sh <command>
#   setup                      first install (asks a few questions), safe to re-run
#   add-user EMAIL "First Last" create a login (prints a one-time password)
#   reset-password EMAIL       new one-time password for an existing login
#   status | logs [service]    what's running / follow logs
#   backup                     database + uploaded files -> infra/trial/backups/
#   restore FILE.tar.gz        put a backup back (replaces current data)
#   update                     pull the latest code, rebuild, restart (migrations run automatically)
#   stop | start               stop or start everything (data is kept)
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
ENV_FILE="$HERE/.env"
dc() { docker compose --project-directory "$HERE" -f "$HERE/docker-compose.yml" --env-file "$ENV_FILE" "$@"; }
say() { printf '\n\033[1m%s\033[0m\n' "$*"; }
die() { printf '\n\033[31mError:\033[0m %s\n' "$*" >&2; exit 1; }
rand() { head -c "$1" /dev/urandom | od -An -tx1 | tr -d ' \n'; }
password() { head -c 24 /dev/urandom | base64 | tr -d '/+=' | cut -c1-16; }
load_env() { [ -f "$ENV_FILE" ] || die "Not set up yet. Run: $0 setup"; set -a; . "$ENV_FILE"; set +a; }

need_docker() {
  command -v docker >/dev/null || die "Docker is not installed. See infra/trial/README.md, step 2."
  docker compose version >/dev/null 2>&1 || die "Docker Compose v2 is missing. See infra/trial/README.md, step 2."
  docker info >/dev/null 2>&1 || die "Can't talk to Docker. Try again with sudo, or add your user to the docker group."
}

kc() { dc exec -T keycloak /opt/keycloak/bin/kcadm.sh "$@" --config /tmp/kcadm.config; }
kc_login() {
  local n=0
  until dc exec -T keycloak /opt/keycloak/bin/kcadm.sh config credentials --config /tmp/kcadm.config \
      --server http://localhost:8080/id --realm master --user admin --password "$KEYCLOAK_ADMIN_PASSWORD" >/dev/null 2>&1; do
    n=$((n+1)); [ $n -gt 90 ] && die "Login service didn't start. Check: $0 logs keycloak"
    sleep 2
  done
}

create_user() { # email, full name, temporary password
  local email=$1 first=${2%% *} last=${2#* } pw=$3
  [ "$last" = "$2" ] && last="-"
  if [ -n "$(kc get users -r office -q email="$email" -q exact=true --fields id --format csv --noquotes)" ]; then
    echo "  $email already has a login"; return 1
  fi
  kc create users -r office -s username="$email" -s email="$email" -s emailVerified=true -s enabled=true \
    -s firstName="$first" -s lastName="$last" >/dev/null
  kc set-password -r office --username "$email" --new-password "$pw" --temporary >/dev/null
}

cmd_setup() {
  need_docker
  if [ ! -f "$ENV_FILE" ]; then
    say "A few questions (press Enter to accept the [default])"
    local domain email owner name
    domain=${OFFICE_DOMAIN:-}; email=${OFFICE_ACME_EMAIL:-}; owner=${OFFICE_OWNER_EMAIL:-}; name=${OFFICE_OWNER_NAME:-}
    [ -n "$domain" ] || read -rp "Domain for this install (e.g. office.mybakery.com): " domain
    [ -n "$domain" ] || die "A domain is required (use localhost to try it on this machine)."
    [ -n "$owner" ] || read -rp "Your email (your login): " owner
    [ -n "$name" ] || read -rp "Your name [Owner]: " name
    [ -n "$email" ] || email=$owner
    umask 077
    cat > "$ENV_FILE" <<ENV
# Generated by office.sh setup on $(date -u +%F). Keep this file secret and backed up.
DOMAIN=$domain
ACME_EMAIL=$email
OWNER_EMAIL=$owner
OWNER_NAME=${name:-Owner}
OWNER_DB_PASSWORD=$(rand 16)
APP_DB_PASSWORD=$(rand 16)
RELAY_DB_PASSWORD=$(rand 16)
KEYCLOAK_DB_PASSWORD=$(rand 16)
KEYCLOAK_ADMIN_PASSWORD=$(rand 16)
API_KEY_PEPPER=$(rand 32)
SECRETS_KEY=$(head -c 32 /dev/urandom | base64)
# Email: "log" only prints emails in the logs. To really send, set MAIL_DRIVER=smtp and SMTP_URL, then: office.sh start
MAIL_DRIVER=log
MAIL_FROM="Office <no-reply@$domain>"
SMTP_URL=
ENV
    echo "  Saved settings to infra/trial/.env"
  fi
  load_env

  say "Building and starting Office (the first time takes 5 to 15 minutes)"
  dc up -d --build

  say "Configuring sign-in"
  kc_login
  local id
  id=$(kc get clients -r office -q clientId=office-web --fields id --format csv --noquotes)
  kc update "clients/$id" -r office -s "redirectUris=[\"https://$DOMAIN/*\"]" -s "webOrigins=[\"https://$DOMAIN\"]" \
    -s "attributes.\"post.logout.redirect.uris\"=https://$DOMAIN##https://$DOMAIN/*"
  # Logins are created by the owner (office.sh add-user); no public sign-up.
  kc update realms/office -s registrationAllowed=false -s displayName=Office
  local pw; pw=$(password)
  if create_user "$OWNER_EMAIL" "$OWNER_NAME" "$pw"; then OWNER_PW=$pw; fi

  say "Waiting for the app"
  local n=0
  until dc exec -T caddy wget -qO- http://api:3000/healthz >/dev/null 2>&1; do
    n=$((n+1)); [ $n -gt 60 ] && die "The app didn't start. Check: $0 logs api"; sleep 2
  done

  say "Office is running: https://$DOMAIN"
  if [ -n "${OWNER_PW:-}" ]; then
    echo "  Sign in with:  $OWNER_EMAIL"
    echo "  One-time password: $OWNER_PW   (you'll choose your own on first sign-in)"
  fi
  echo "  Next: create your organization, then follow infra/trial/README.md step 6."
}

cmd_add_user() {
  [ $# -ge 1 ] || die "Usage: $0 add-user EMAIL \"First Last\""
  load_env; kc_login
  local pw; pw=$(password)
  if create_user "$1" "${2:-$1}" "$pw"; then
    say "Login created for $1"
    echo "  One-time password: $pw   (they choose their own on first sign-in)"
    echo "  Send them https://$DOMAIN, then add them in Office: Admin -> Members (after their first sign-in)."
  fi
}

cmd_reset_password() {
  [ $# -ge 1 ] || die "Usage: $0 reset-password EMAIL"
  load_env; kc_login
  [ -n "$(kc get users -r office -q email="$1" -q exact=true --fields id --format csv --noquotes)" ] || die "No login for $1"
  local pw; pw=$(password)
  kc set-password -r office --username "$1" --new-password "$pw" --temporary >/dev/null
  say "New one-time password for $1: $pw"
}

cmd_backup() {
  load_env
  local ts dir; ts=$(date -u +%Y%m%d-%H%M%S); dir="$HERE/backups"; mkdir -p "$dir"
  local tmp; tmp=$(mktemp -d)
  say "Backing up database"
  dc exec -T postgres pg_dumpall -U office_owner | gzip > "$tmp/databases.sql.gz"
  say "Backing up uploaded files"
  docker run --rm -v office-trial_files:/data:ro -v "$tmp":/out alpine:3.20 tar czf /out/files.tar.gz -C /data .
  cp "$ENV_FILE" "$tmp/env"
  tar czf "$dir/office-$ts.tar.gz" -C "$tmp" . && rm -rf "$tmp"
  say "Saved $dir/office-$ts.tar.gz"
  echo "  Copy it off this server (it contains your secrets and data)."
}

cmd_restore() {
  [ -f "${1:-}" ] || die "Usage: $0 restore infra/trial/backups/office-<date>.tar.gz"
  load_env
  read -rp "This replaces ALL current data with the backup. Type RESTORE to continue: " ok
  [ "$ok" = RESTORE ] || die "Cancelled."
  local tmp; tmp=$(mktemp -d); tar xzf "$1" -C "$tmp"
  cmp -s "$tmp/env" "$ENV_FILE" || { cp "$ENV_FILE" "$ENV_FILE.before-restore"; cp "$tmp/env" "$ENV_FILE"; load_env; }
  dc down
  docker volume rm office-trial_pgdata office-trial_files >/dev/null 2>&1 || true
  dc up -d postgres
  until dc exec -T postgres pg_isready -U office_owner -d office >/dev/null 2>&1; do sleep 2; done
  sleep 3
  gunzip -c "$tmp/databases.sql.gz" | dc exec -T postgres psql -q -U office_owner -d postgres >/dev/null
  docker run --rm -v office-trial_files:/data -v "$tmp":/in:ro alpine:3.20 sh -c "tar xzf /in/files.tar.gz -C /data && chown -R 65532:65532 /data"
  rm -rf "$tmp"
  dc up -d
  say "Restored. Office is starting at https://$DOMAIN"
}

cmd_update() {
  load_env; need_docker
  say "Getting the latest code"
  git -C "$HERE" pull --ff-only
  say "Rebuilding and restarting (migrations run automatically)"
  dc up -d --build
  docker image prune -f >/dev/null
  say "Updated: https://$DOMAIN"
}

case "${1:-}" in
  setup) shift; cmd_setup "$@" ;;
  add-user) shift; cmd_add_user "$@" ;;
  reset-password) shift; cmd_reset_password "$@" ;;
  status) load_env; dc ps ;;
  logs) load_env; shift; dc logs -f --tail 100 "$@" ;;
  backup) cmd_backup ;;
  restore) shift; cmd_restore "$@" ;;
  update) cmd_update ;;
  stop) load_env; dc stop ;;
  start) load_env; dc up -d ;;
  *) sed -n '2,10p' "$0" | sed 's/^# \{0,1\}//'; exit 1 ;;
esac
